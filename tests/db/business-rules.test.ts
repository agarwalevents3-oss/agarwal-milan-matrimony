import { beforeAll, afterAll, beforeEach, describe, expect, it } from "vitest";
import type { PGlite } from "@electric-sql/pglite";
import { createTestDb, asUser } from "../../scripts/pg-harness.mjs";
import { seed, type Cast } from "./fixtures";

/**
 * Rules the PRD states as absolutes. Each is enforced in the database, so these
 * tests hold even against a caller wielding the service-role key — which is
 * the point: an application bug cannot break them.
 */
describe("Business rules enforced by the database", () => {
  let db: PGlite;
  let cast: Cast;

  beforeAll(async () => {
    db = await createTestDb();
    cast = await seed(db);
  });

  afterAll(async () => db?.close());

  beforeEach(async () => {
    await db.query(`delete from public.matches`);
    await db.query(`delete from public.interests`);
    await db.query(`delete from public.notifications`);
  });

  describe("registration lifecycle (PRD §14)", () => {
    it("issues sequential REG ids generated by the database (PRD §6.2)", async () => {
      const { rows } = await db.query<{ registration_id: string }>(
        `select registration_id from public.registrations order by registration_id`,
      );
      expect(rows.length).toBeGreaterThanOrEqual(5);
      for (const r of rows) expect(r.registration_id).toMatch(/^REG\d{6}$/);
      expect(new Set(rows.map((r) => r.registration_id)).size).toBe(rows.length);
    });

    it("rejects a jump straight from PAYMENT_PENDING to VERIFIED", async () => {
      await expect(
        db.query(`update public.registrations set status = 'VERIFIED' where user_id = $1`, [cast.dave]),
      ).rejects.toThrow(/Illegal registration transition/);
    });

    it("REFUSES to verify a registration that has not been paid for (PRD §6.5)", async () => {
      // Walk Dave to the review queue but leave payment unpaid.
      await db.query(`update public.registrations set status = 'PAYMENT_FAILED'  where user_id = $1`, [cast.dave]);
      await db.query(`update public.registrations set status = 'PAYMENT_PENDING' where user_id = $1`, [cast.dave]);
      await db.query(`update public.registrations set status = 'PAYMENT_SUCCESS' where user_id = $1`, [cast.dave]);
      await db.query(`update public.registrations set status = 'PENDING_VERIFICATION' where user_id = $1`, [cast.dave]);

      await expect(
        db.query(`update public.registrations set status = 'VERIFIED' where user_id = $1`, [cast.dave]),
      ).rejects.toThrow(/payment is not SUCCESS/);
    });

    it("flips the browsable flag only when the registration reaches VERIFIED", async () => {
      const { rows } = await db.query<{ is_verified: boolean }>(
        `select is_verified from public.profiles where user_id = $1`, [cast.carol]);
      expect(rows[0].is_verified).toBe(false);
    });

    it("treats DELETED as terminal", async () => {
      const auth = await db.query<{ id: string }>(
        `insert into auth.users (phone, email) values ('+919000009999', 'tmp@example.com') returning id`);
      const id = auth.rows[0].id;
      await db.query(
        `insert into public.users (id, mobile, email) values ($1, '+919000009999', 'tmp@example.com')`, [id]);
      await db.query(`insert into public.profiles (user_id, full_name, gender) values ($1, 'Temp', 'MALE')`, [id]);
      await db.query(`insert into public.registrations (user_id) values ($1)`, [id]);
      await db.query(`update public.registrations set status = 'DELETED' where user_id = $1`, [id]);
      await expect(
        db.query(`update public.registrations set status = 'SUBMITTED' where user_id = $1`, [id]),
      ).rejects.toThrow(/Illegal registration transition/);
    });
  });

  describe("Aadhaar is write-once, forever (PRD §18.1)", () => {
    it("cannot be updated — not even by the service role", async () => {
      await expect(
        db.query(`update public.documents set storage_path = 'hacked' where document_type = 'AADHAAR'`),
      ).rejects.toThrow(/Aadhaar documents are locked/);
    });

    it("cannot be deleted — not even by the service role", async () => {
      await expect(
        db.query(`delete from public.documents where document_type = 'AADHAAR'`),
      ).rejects.toThrow(/Aadhaar documents cannot be deleted/);
    });

    it("cannot be recorded without captured consent", async () => {
      await expect(
        db.query(
          `insert into public.documents (user_id, document_type, storage_path, mime_type, size_bytes, consent_given)
           values ($1, 'AADHAAR', 'x/y.webp', 'image/webp', 1000, false)`, [cast.dave]),
      ).rejects.toThrow(/documents_aadhaar_needs_consent/);
    });

    it("allows only one per user", async () => {
      await expect(
        db.query(
          `insert into public.documents (user_id, document_type, storage_path, mime_type, size_bytes,
                                         consent_given, consent_text, consent_timestamp)
           values ($1, 'AADHAAR', 'x/second.webp', 'image/webp', 1000, true, 'consent', now())`, [cast.alice]),
      ).rejects.toThrow(/documents_one_aadhaar_per_user/);
    });
  });

  describe("profile edit rules (PRD §8.3)", () => {
    it("lets a user update their own optional fields", async () => {
      await asUser(db, cast.alice,
        `update public.profiles set occupation = 'Architect', height_cm = 165 where user_id = $1`, [cast.alice]);
      const { rows } = await asUser(db, cast.alice,
        `select occupation, height_cm from public.profiles where user_id = $1`, [cast.alice]);
      expect(rows[0]).toMatchObject({ occupation: "Architect", height_cm: 165 });
    });

    it("blocks renaming after registration", async () => {
      await expect(
        asUser(db, cast.alice, `update public.profiles set full_name = 'Someone Else' where user_id = $1`, [cast.alice]),
      ).rejects.toThrow(/full_name cannot be changed/);
    });

    it("blocks changing date of birth, so age filters cannot be gamed", async () => {
      await expect(
        asUser(db, cast.alice, `update public.profiles set dob = '2005-01-01' where user_id = $1`, [cast.alice]),
      ).rejects.toThrow(/date of birth cannot be changed/);
    });

    it("blocks a user from verifying themselves", async () => {
      await expect(
        asUser(db, cast.carol, `update public.profiles set is_verified = true where user_id = $1`, [cast.carol]),
      ).rejects.toThrow(/is_verified is not user-writable/);
    });

    it("blocks writing photo paths directly, forcing the upload route", async () => {
      await expect(
        asUser(db, cast.alice, `update public.profiles set photo_path = 'other-user/photo.webp' where user_id = $1`, [cast.alice]),
      ).rejects.toThrow(/use \/api\/profile\/photo/);
    });

    it("blocks editing anyone else's profile", async () => {
      const res = await asUser(db, cast.alice,
        `update public.profiles set occupation = 'Tampered' where user_id = $1`, [cast.bob]);
      expect(res.affectedRows ?? 0).toBe(0);
    });
  });

  describe("interests (PRD §10.1)", () => {
    it("notifies the receiver and the admin when sent", async () => {
      await asUser(db, cast.alice, `select public.send_interest($1)`, [cast.bob]);
      const { rows } = await db.query<{ type: string; recipient_user_id: string }>(
        `select type, recipient_user_id from public.notifications order by created_at`);
      expect(rows.map((r) => r.type)).toEqual(["INTEREST_RECEIVED", "ADMIN_NOTIFICATION"]);
      expect(rows[0].recipient_user_id).toBe(cast.bob);
      expect(rows[1].recipient_user_id).toBe(cast.admin);
    });

    it("refuses a duplicate to the same profile (PRD §10.1)", async () => {
      await asUser(db, cast.alice, `select public.send_interest($1)`, [cast.bob]);
      await expect(
        asUser(db, cast.alice, `select public.send_interest($1)`, [cast.bob]),
      ).rejects.toThrow(/already sent an interest/);
    });

    it("refuses an interest in oneself", async () => {
      await expect(
        asUser(db, cast.alice, `select public.send_interest($1)`, [cast.alice]),
      ).rejects.toThrow(/cannot send an interest to yourself/);
    });

    it("refuses an interest from an unverified user (PRD §7.2)", async () => {
      await expect(
        asUser(db, cast.carol, `select public.send_interest($1)`, [cast.bob]),
      ).rejects.toThrow(/Only verified users can send interests/);
    });

    it("refuses an interest toward a profile that is not verified", async () => {
      await expect(
        asUser(db, cast.alice, `select public.send_interest($1)`, [cast.carol]),
      ).rejects.toThrow(/not available/);
    });

    it("lets only the receiver answer", async () => {
      const sent = await asUser<{ send_interest: string }>(db, cast.alice,
        `select (public.send_interest($1)).id as send_interest`, [cast.bob]);
      const id = sent.rows[0].send_interest;
      await expect(
        asUser(db, cast.alice, `select public.respond_to_interest($1, 'ACCEPT')`, [id]),
      ).rejects.toThrow(/not the recipient/);
    });

    it("refuses a second answer to the same interest", async () => {
      const sent = await asUser<{ id: string }>(db, cast.alice,
        `select (public.send_interest($1)).id as id`, [cast.bob]);
      const id = sent.rows[0].id;
      await asUser(db, cast.bob, `select public.respond_to_interest($1, 'REJECT')`, [id]);
      await expect(
        asUser(db, cast.bob, `select public.respond_to_interest($1, 'ACCEPT')`, [id]),
      ).rejects.toThrow(/already been answered/);
    });
  });

  describe("mutual match (PRD §10.4)", () => {
    /** Interest must exist AND be accepted in BOTH directions — see docs/DECISIONS.md. */
    async function sendAndAccept(from: string, to: string) {
      const sent = await asUser<{ id: string }>(db, from, `select (public.send_interest($1)).id as id`, [to]);
      return asUser<{ respond_to_interest: { matched: boolean; match_id?: string; new?: boolean } }>(
        db, to, `select public.respond_to_interest($1, 'ACCEPT') as respond_to_interest`, [sent.rows[0].id],
      );
    }

    it("does NOT match on a one-sided accept", async () => {
      const res = await sendAndAccept(cast.alice, cast.bob);
      expect(res.rows[0].respond_to_interest.matched).toBe(false);
      const { rows } = await db.query(`select id from public.matches`);
      expect(rows).toHaveLength(0);
    });

    it("rejecting creates no match and notifies the sender", async () => {
      const sent = await asUser<{ id: string }>(db, cast.alice, `select (public.send_interest($1)).id as id`, [cast.bob]);
      const res = await asUser<{ r: { matched: boolean; status: string } }>(
        db, cast.bob, `select public.respond_to_interest($1, 'REJECT') as r`, [sent.rows[0].id]);
      expect(res.rows[0].r).toMatchObject({ status: "REJECTED", matched: false });
      const { rows } = await db.query(`select id from public.matches`);
      expect(rows).toHaveLength(0);
      const notifs = await db.query<{ type: string }>(
        `select type from public.notifications where type = 'INTEREST_REJECTED'`);
      expect(notifs.rows).toHaveLength(1);
    });

    it("creates EXACTLY ONE match when interest is accepted both ways (PRD §27)", async () => {
      await sendAndAccept(cast.alice, cast.bob);
      const res = await sendAndAccept(cast.bob, cast.alice);

      expect(res.rows[0].respond_to_interest).toMatchObject({ matched: true, new: true });

      const { rows } = await db.query<{ user_a_id: string; user_b_id: string }>(
        `select user_a_id, user_b_id from public.matches`);
      expect(rows).toHaveLength(1);
      // Canonical ordering is what makes the pair uniquely constrainable.
      expect(rows[0].user_a_id < rows[0].user_b_id).toBe(true);
      expect([rows[0].user_a_id, rows[0].user_b_id].sort()).toEqual([cast.alice, cast.bob].sort());
    });

    it("notifies both users and the admin on a match (PRD §10.5)", async () => {
      await sendAndAccept(cast.alice, cast.bob);
      await sendAndAccept(cast.bob, cast.alice);

      const { rows } = await db.query<{ recipient_user_id: string }>(
        `select recipient_user_id from public.notifications where type = 'MATCH_CREATED'`);
      expect(rows.map((r) => r.recipient_user_id).sort()).toEqual([cast.alice, cast.bob].sort());

      const admin = await db.query<{ n: number }>(
        `select count(*)::int as n from public.notifications
          where recipient_user_id = $1 and title = 'New match'`, [cast.admin]);
      expect(admin.rows[0].n).toBe(1);
    });

    it("cannot be duplicated by the pair matching again", async () => {
      await sendAndAccept(cast.alice, cast.bob);
      await sendAndAccept(cast.bob, cast.alice);
      await expect(
        db.query(`insert into public.matches (user_a_id, user_b_id)
                  values (least($1::uuid,$2::uuid), greatest($1::uuid,$2::uuid))`, [cast.alice, cast.bob]),
      ).rejects.toThrow(/matches_unique_pair/);
    });

    it("rejects an out-of-order pair outright", async () => {
      await expect(
        db.query(`insert into public.matches (user_a_id, user_b_id)
                  values (greatest($1::uuid,$2::uuid), least($1::uuid,$2::uuid))`, [cast.alice, cast.bob]),
      ).rejects.toThrow(/matches_canonical_order/);
    });
  });

  describe("notifications", () => {
    it("lets a user mark their own notification read", async () => {
      await asUser(db, cast.alice, `select public.send_interest($1)`, [cast.bob]);
      await asUser(db, cast.bob, `update public.notifications set is_read = true where recipient_user_id = $1`, [cast.bob]);
      const { rows } = await db.query<{ is_read: boolean }>(
        `select is_read from public.notifications where recipient_user_id = $1`, [cast.bob]);
      expect(rows[0].is_read).toBe(true);
    });

    it("does NOT let a user rewrite a notification's contents", async () => {
      await asUser(db, cast.alice, `select public.send_interest($1)`, [cast.bob]);
      await expect(
        asUser(db, cast.bob, `update public.notifications set title = 'Forged' where recipient_user_id = $1`, [cast.bob]),
      ).rejects.toThrow(/permission denied/i);
    });
  });

  describe("rate limiting", () => {
    it("allows up to the limit then refuses", async () => {
      const key = "test:" + Date.now();
      const results: boolean[] = [];
      for (let i = 0; i < 5; i++) {
        const { rows } = await db.query<{ ok: boolean }>(
          `select public.check_rate_limit($1, 3, 60) as ok`, [key]);
        results.push(rows[0].ok);
      }
      expect(results).toEqual([true, true, true, false, false]);
    });
  });
});
